function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="ko">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const pathname = useRouterState({ select: (state) => state.location.pathname });
  const path = pathname.replace(/\/+$/, "") || "/";
  const priceRoute = path === "/" || path === "/explore" || path === "/compare" ||
    path === "/me" || path === "/report" || path === "/diagnose" ||
    path === "/coach" || path.startsWith("/coach/") || path.startsWith("/car/");

  useEffect(() => {
    void hydrateCars().catch(() => {});
    const { data: sub } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
      if (event === "SIGNED_IN") {
        void hydrateWatchlistFromServer();
        void hydratePrefsFromServer();
        void hydrateAlertsFromServer();
      }
    });
    // 새로고침으로 이미 세션이 있는 경우
    void hydrateWatchlistFromServer();
    void hydratePrefsFromServer();
    void hydrateAlertsFromServer();
    return () => sub.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {priceRoute ? <PriceReviewGate /> : <Outlet />}
      <Toaster richColors position="top-center" />
      <SplashScreen />
    </QueryClientProvider>
  );
}
